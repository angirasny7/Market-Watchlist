export interface MasterStockItem {
  symbol: string;
  companyName: string;
  sector: string;
  exchange: string;
  currency: string;
  currentPrice: number;
  changeAmount: number;
  changePercent: number;
  volume: bigint;
  avgVolume20D: bigint;
  marketCap: string;
  peRatio: number | null;
  high52w: number;
  low52w: number;
  tags: string[];
  sparkline: Array<{ date: string; price: number }>;
}

function genSparkline(basePrice: number, changePercent: number): Array<{ date: string; price: number }> {
  const points = [];
  const days = ['Day -6', 'Day -5', 'Day -4', 'Day -3', 'Day -2', 'Yesterday', 'Today'];
  const startPrice = basePrice / (1 + changePercent / 100);
  for (let i = 0; i < days.length; i++) {
    const progress = i / (days.length - 1);
    const jitter = (Math.sin(i * 1.5) * 0.015);
    const price = +(startPrice * (1 + (changePercent / 100) * progress + jitter)).toFixed(2);
    points.push({ date: days[i], price: i === days.length - 1 ? basePrice : price });
  }
  return points;
}

